function woodBlocks(w: string): string[] {
  const nether = w === 'crimson' || w === 'warped';
  const out = [
    `${w}_stairs`,
    `${w}_slab`,
    `${w}_fence`,
    `${w}_fence_gate`,
    `${w}_door`,
    `${w}_trapdoor`,
    `${w}_button`,
    `${w}_pressure_plate`,
    `${w}_sign`,
    `${w}_wall_sign`,
    `${w}_hanging_sign`,
    `${w}_wall_hanging_sign`,
  ];
  if (nether) out.push(`${w}_stem`, `stripped_${w}_stem`, `${w}_hyphae`, `stripped_${w}_hyphae`);
  else if (w === 'bamboo') out.push('bamboo_block', 'stripped_bamboo_block');
  else out.push(`${w}_log`, `stripped_${w}_log`, `${w}_wood`, `stripped_${w}_wood`, `${w}_leaves`);
  if (!nether && w !== 'bamboo' && w !== 'mangrove')
    out.push(`${w}_sapling`, `potted_${w}_sapling`);
  return out;
}

