export function knownBlockNames(): string[] {
  const names = new Set<string>(PLAIN_CUBES);
  for (const n of NAMED_BLOCKS) names.add(n);
  for (const w of WOODS) for (const n of woodBlocks(w)) names.add(n);
  for (const m of STAIR_SLAB_MATERIALS) {
    names.add(`${m}_stairs`);
    names.add(`${m}_slab`);
  }
  for (const m of SLAB_ONLY) names.add(`${m}_slab`);
  for (const m of WALL_MATERIALS) names.add(`${m}_wall`);
  for (const c of COLORS) {
    for (const s of [
      'carpet',
      'glazed_terracotta',
      'stained_glass',
      'stained_glass_pane',
      'bed',
      'banner',
      'wall_banner',
      'candle',
      'candle_cake',
      'shulker_box',
    ]) {
      names.add(`${c}_${s}`);
    }
  }
  for (const n of [...names]) {
    if (
      /copper|cut_copper/.test(n) &&
      !n.startsWith('waxed_') &&
      !/_ore$/.test(n) &&
      n !== 'raw_copper_block'
    ) {
      names.add(`waxed_${n}`);
    }
  }
  return [...names].sort();
}

